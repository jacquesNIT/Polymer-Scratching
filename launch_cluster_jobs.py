#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Batch launcher for ScratchSimulation on the cluster.

RUN THIS ON THE LOGIN NODE. 
The site wrapper performs its own `sbatch`submission, so this script simply calls it once per job -- never wrap this script itself in sbatch.

Each job gets a fully isolated directory (cluster_jobs/<batch>/job_XXX/) containing an auto-generated driver script; the wrapper is invoked with that
directory as working directory, so concurrent Abaqus sessions never share .odb / .sta / .lck / .rpy files. Inside the job, run_parameter_study adds a
second isolation level (runs/<study>_cXXXofYYY + unique job names).

MODES
  sweep   Split one study into N chunk jobs (round-robin slices cases[i::N]). The canonical use: the 1024-case QMC material sweep.
  multi   One job per study spec 'study[:family[:tag]]' -- launch several different studies (or the same study on several families) at once.
  status  Progress table of a batch: results produced / expected, lock files (job probably running), last activity.
  gather  Collect every *_Results.csv (optionally .sta/.odb) of a batch into a single folder, ready for WinSCP retrieval.

EXAMPLES (resource defaults mirror submit.sh: -p q36 -c 36 -m 120 -t 10:00:00)
  python3 launch_cluster_jobs.py sweep --study material --family elastomer_mr --chunks 32
  python3 launch_cluster_jobs.py sweep --study material --chunks 64 --cpus 18 --time 20:00:00
  python3 launch_cluster_jobs.py sweep --study material --chunks 32 --only 4,17,29   # resubmit failed chunks
  python3 launch_cluster_jobs.py multi --jobs mesh:elastomer_mr friction:glassy_pc models:elastomer_ve
  python3 launch_cluster_jobs.py status --batch cluster_jobs/material_20260705_101530
  python3 launch_cluster_jobs.py gather --batch cluster_jobs/material_20260705_101530 --out merged_material

LICENSE-TOKEN SIZING (read before launching 32+ jobs)
  Abaqus tokens scale sublinearly with cores, roughly 5*N^0.422:
      1 cpu -> 5, 4 -> 8, 9 -> 12, 18 -> 17, 36 -> 22 tokens.
  K concurrent jobs consume K * tokens(cpus). Size --chunks and --cpus so the
  batch fits the site token pool, otherwise late jobs abort at license
  checkout. Fewer/larger jobs are more token-efficient per simulation; more/
  smaller jobs finish sooner if tokens and nodes allow. Splitting a node
  (e.g. --cpus 18 -> 2 jobs/node, --cpus 9 -> 4 jobs/node) is how "diviser
  l'utilisation des nodes" is achieved: the wrapper -c and the Abaqus
  num_cpus are kept consistent automatically (cpus=K token).
"""

import argparse
import glob
import json
import os
import subprocess
import sys
import time

DEFAULT_PARTITION = "q36"
DEFAULT_CPUS = 36
DEFAULT_MEM = 120
DEFAULT_TIME = "10:00:00"
DEFAULT_WRAPPER = "subabqpy2025-old"
BATCH_ROOT = "cluster_jobs"

DRIVER_TEMPLATE = '''# Auto-generated by launch_cluster_jobs.py -- do not edit.
# Batch : {batch}
# Job   : {jobname}
# Argv  : {tokens}
import sys, os
sys.dont_write_bytecode = True    # concurrent jobs share the repo: no .pyc races
REPO = {repo!r}                   # ScratchSimulation package directory (absolute)
SCRIPT = os.path.join(REPO, "run_parameter_study.py")
sys.path.insert(0, os.path.dirname(REPO))
sys.argv = [SCRIPT, "--"] + {tokens!r}
exec(compile(open(SCRIPT).read(), SCRIPT, "exec"),
     {{"__name__": "__main__", "__file__": SCRIPT}})
'''


# ----------------------------------------------------------------- helpers
def find_repo():
    """This script lives inside the ScratchSimulation package directory."""
    here = os.path.dirname(os.path.abspath(__file__))
    if os.path.exists(os.path.join(here, "run_parameter_study.py")):
        return here
    raise SystemExit("run_parameter_study.py not found next to this script "
                     "(%s): launch_cluster_jobs.py must live in the "
                     "ScratchSimulation directory." % here)


def estimate_tokens(cpus):
    return int(round(5.0 * (max(int(cpus), 1) ** 0.422)))


def count_sweep_cases(repo):
    """Row count of the QMC sweep CSV (None if absent)."""
    path = os.path.join(repo, "material_parameters",
                        "polymer_MR_material_parameter_sweep.csv")
    if not os.path.exists(path):
        return None
    with open(path, "r") as f:
        n = sum(1 for _ in f) - 1
    return max(n, 0)


def make_job(batch_dir, jobname, tokens, repo, batch_name, expected=None):
    jobdir = os.path.join(batch_dir, jobname)
    if not os.path.exists(jobdir):
        os.makedirs(jobdir)
    driver = os.path.join(jobdir, "driver.py")
    with open(driver, "w") as f:
        f.write(DRIVER_TEMPLATE.format(batch=batch_name, jobname=jobname,
                                       tokens=tokens, repo=repo))
    return {"name": jobname, "dir": os.path.abspath(jobdir),
            "tokens": tokens, "expected": expected}


def submit_job(job, args):
    script_arg = "driver" + (args.script_suffix or "")
    wrapper = args.wrapper
    if os.path.sep in wrapper or wrapper.startswith("."):
        # relative/local wrapper path: resolve NOW, because the submission
        # runs with cwd = job directory (site wrappers on PATH are unaffected)
        wrapper = os.path.abspath(wrapper)
    cmd = [wrapper, "-p", args.partition, "-c", str(args.cpus),
           "-m", str(args.mem), "-t", args.time, script_arg]
    print("  [%s] (cwd=%s)\n      %s" % (job["name"], job["dir"], " ".join(cmd)))
    if args.dry_run:
        return 0
    try:
        rc = subprocess.call(cmd, cwd=job["dir"])
    except OSError as exc:
        print("  !! could not invoke wrapper for %s: %s" % (job["name"], exc))
        rc = -1
    if rc != 0:
        print("  !! wrapper returned %d for %s" % (rc, job["name"]))
    if args.sleep > 0:
        time.sleep(args.sleep)
    return rc


def write_manifest(batch_dir, payload):
    with open(os.path.join(batch_dir, "manifest.json"), "w") as f:
        json.dump(payload, f, indent=2)
    print(">>> Manifest: %s" % os.path.join(batch_dir, "manifest.json"))


def load_manifest(batch_dir):
    path = os.path.join(batch_dir, "manifest.json")
    if not os.path.exists(path):
        raise SystemExit("No manifest.json in %s (is this a batch directory?)" % batch_dir)
    with open(path, "r") as f:
        return json.load(f)


def new_batch_dir(label):
    name = "%s_%s" % (label, time.strftime("%Y%m%d_%H%M%S"))
    batch_dir = os.path.join(BATCH_ROOT, name)
    os.makedirs(batch_dir)
    return batch_dir, name


def print_token_budget(n_jobs, cpus):
    tok = estimate_tokens(cpus)
    print(">>> License budget: %d jobs x ~%d tokens = ~%d tokens if all run "
          "concurrently (formula ~5*N^0.422 -- check against the site pool)."
          % (n_jobs, tok, n_jobs * tok))


# ----------------------------------------------------------------- modes
def mode_sweep(args):
    repo = find_repo()
    if args.chunks < 1:
        raise SystemExit("--chunks must be >= 1")

    if args.only:
        indices = sorted({int(x) for x in args.only.split(",")})
        bad = [i for i in indices if not (0 <= i < args.chunks)]
        if bad:
            raise SystemExit("--only indices out of range 0..%d: %s" % (args.chunks - 1, bad))
    else:
        indices = list(range(args.start, min(args.chunks, args.start + (args.limit or args.chunks))))

    n_global = count_sweep_cases(repo) if args.study == "material" else None
    label = args.tag or args.study
    batch_dir, batch_name = new_batch_dir(label)

    jobs = []
    for i in indices:
        tokens = [args.study]
        if args.family:
            tokens.append(args.family)
        tokens.append("%d/%d" % (i, args.chunks))
        tokens.append("cpus=%d" % args.cpus)
        if args.tag:
            tokens.append("tag=%s" % args.tag)
        expected = len(range(i, n_global, args.chunks)) if n_global else None
        jobs.append(make_job(batch_dir, "job_%03d" % i, tokens, repo,
                             batch_name, expected))

    print(">>> Batch %s : study '%s'%s, %d chunk job(s) of %d total chunks%s"
          % (batch_name, args.study,
             (" / family '%s'" % args.family) if args.family else "",
             len(jobs), args.chunks,
             (", %d global cases" % n_global) if n_global else ""))
    print_token_budget(len(jobs), args.cpus)

    # Manifest BEFORE submission: a failure mid-batch must leave a usable
    # manifest for status/gather/--only resubmission.
    write_manifest(batch_dir, {
        "mode": "sweep", "study": args.study, "family": args.family,
        "chunks": args.chunks, "cpus": args.cpus, "partition": args.partition,
        "mem": args.mem, "time": args.time, "wrapper": args.wrapper,
        "n_global_cases": n_global, "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "dry_run": bool(args.dry_run), "jobs": jobs,
    })

    for job in jobs:
        submit_job(job, args)
    if args.dry_run:
        print(">>> DRY RUN: nothing submitted (drivers and manifest were generated).")


def mode_multi(args):
    repo = find_repo()
    batch_dir, batch_name = new_batch_dir(args.tag or "multi")

    jobs = []
    for k, spec in enumerate(args.jobs):
        parts = spec.split(":")
        study = parts[0]
        family = parts[1] if len(parts) > 1 and parts[1] else None
        tag = parts[2] if len(parts) > 2 and parts[2] else None
        tokens = [study]
        if family:
            tokens.append(family)
        tokens.append("cpus=%d" % args.cpus)
        if tag:
            tokens.append("tag=%s" % tag)
        jobname = "job_%03d_%s" % (k, "_".join(p for p in (study, family, tag) if p))
        jobs.append(make_job(batch_dir, jobname, tokens, repo, batch_name))

    print(">>> Batch %s : %d independent study job(s)" % (batch_name, len(jobs)))
    print_token_budget(len(jobs), args.cpus)

    write_manifest(batch_dir, {
        "mode": "multi", "specs": args.jobs, "cpus": args.cpus,
        "partition": args.partition, "mem": args.mem, "time": args.time,
        "wrapper": args.wrapper, "created": time.strftime("%Y-%m-%d %H:%M:%S"),
        "dry_run": bool(args.dry_run), "jobs": jobs,
    })

    for job in jobs:
        submit_job(job, args)
    if args.dry_run:
        print(">>> DRY RUN: nothing submitted (drivers and manifest were generated).")


def _job_stats(jobdir):
    csvs = glob.glob(os.path.join(jobdir, "runs", "*", "SimDataOutputs", "*_Results.csv"))
    lcks = glob.glob(os.path.join(jobdir, "runs", "*", "*.lck"))
    activity = 0.0
    for pat in ("*.sta", "*.odb", "*.log", "*.msg", "*_Results.csv"):
        for f in glob.glob(os.path.join(jobdir, "runs", "*", pat)):
            activity = max(activity, os.path.getmtime(f))
        for f in glob.glob(os.path.join(jobdir, "runs", "*", "SimDataOutputs", pat)):
            activity = max(activity, os.path.getmtime(f))
    return len(csvs), bool(lcks), activity


def mode_status(args):
    man = load_manifest(args.batch)
    now = time.time()
    print("Batch: %s  (mode=%s, created %s)" % (args.batch, man.get("mode"), man.get("created")))
    print("%-28s %10s %8s %14s" % ("job", "results", "lock", "last activity"))
    tot, tot_exp = 0, 0
    for job in man["jobs"]:
        n, locked, act = _job_stats(job["dir"])
        exp = job.get("expected")
        tot += n
        tot_exp += exp or 0
        age = ("%.0f min ago" % ((now - act) / 60.0)) if act else "-"
        res = ("%d/%d" % (n, exp)) if exp else str(n)
        flag = ""
        if exp and n >= exp and not locked:
            flag = "  DONE"
        elif locked:
            flag = "  running?"
        print("%-28s %10s %8s %14s%s" % (job["name"], res, "yes" if locked else "no", age, flag))
    if tot_exp:
        print("TOTAL: %d / %d results (%.1f%%)" % (tot, tot_exp, 100.0 * tot / max(tot_exp, 1)))
    else:
        print("TOTAL: %d results" % tot)


def mode_gather(args):
    man = load_manifest(args.batch)
    out = args.out or (os.path.normpath(args.batch) + "_merged")
    if not os.path.exists(out):
        os.makedirs(out)
    exts = [e.strip().lower() for e in args.exts.split(",") if e.strip()]
    patterns = {"csv": "*_Results.csv", "sta": "*.sta", "odb": "*.odb"}

    import shutil
    n_copied, collisions = 0, 0
    for job in man["jobs"]:
        for ext in exts:
            pat = patterns.get(ext)
            if not pat:
                continue
            for src in sorted(glob.glob(os.path.join(job["dir"], "runs", "*",
                                                     "SimDataOutputs", pat))):
                dest = os.path.join(out, os.path.basename(src))
                if os.path.exists(dest):
                    dest = os.path.join(out, "%s__%s" % (job["name"], os.path.basename(src)))
                    collisions += 1
                shutil.copy2(src, dest)
                n_copied += 1
    print(">>> Gathered %d file(s) into %s (%d name collision(s) prefixed by job name)."
          % (n_copied, out, collisions))
    exp = sum(j.get("expected") or 0 for j in man["jobs"])
    if exp and "csv" in exts:
        n_csv = len(glob.glob(os.path.join(out, "*_Results.csv"))) \
            + len(glob.glob(os.path.join(out, "*__*_Results.csv")))
        print(">>> Completion: %d / %d expected CSVs." % (n_csv, exp))


# ----------------------------------------------------------------- CLI
def add_resource_args(p):
    p.add_argument("--partition", default=DEFAULT_PARTITION)
    p.add_argument("--cpus", type=int, default=DEFAULT_CPUS,
                   help="cores per job: passed to the wrapper -c AND forwarded "
                        "to Abaqus via the cpus= token (kept consistent)")
    p.add_argument("--mem", type=int, default=DEFAULT_MEM)
    p.add_argument("--time", default=DEFAULT_TIME)
    p.add_argument("--wrapper", default=DEFAULT_WRAPPER)
    p.add_argument("--script-suffix", default="",
                   help="appended to the driver name given to the wrapper "
                        "(use '.py' if your wrapper wants the extension)")
    p.add_argument("--sleep", type=float, default=0.5,
                   help="pause between submissions [s]")
    p.add_argument("--dry-run", action="store_true",
                   help="generate drivers + manifest, print commands, submit nothing")
    p.add_argument("--tag", default=None, help="free label (batch name + run-dir suffix)")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="mode")

    p = sub.add_parser("sweep", help="split one study into N chunk jobs")
    p.add_argument("--study", required=True)
    p.add_argument("--family", default=None)
    p.add_argument("--chunks", type=int, required=True)
    p.add_argument("--start", type=int, default=0, help="first chunk index to submit")
    p.add_argument("--limit", type=int, default=None, help="submit at most K chunks")
    p.add_argument("--only", default=None,
                   help="comma-separated chunk indices (resubmit failures), e.g. 4,17,29")
    add_resource_args(p)

    p = sub.add_parser("multi", help="one job per study spec")
    p.add_argument("--jobs", nargs="+", required=True,
                   metavar="STUDY[:FAMILY[:TAG]]")
    add_resource_args(p)

    p = sub.add_parser("status", help="progress table of a batch")
    p.add_argument("--batch", required=True)

    p = sub.add_parser("gather", help="collect batch results into one folder")
    p.add_argument("--batch", required=True)
    p.add_argument("--out", default=None)
    p.add_argument("--exts", default="csv", help="csv[,sta][,odb]")

    args = ap.parse_args(argv)
    if args.mode == "sweep":
        mode_sweep(args)
    elif args.mode == "multi":
        mode_multi(args)
    elif args.mode == "status":
        mode_status(args)
    elif args.mode == "gather":
        mode_gather(args)
    else:
        ap.print_help()
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())